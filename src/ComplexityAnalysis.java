public class ComplexityAnalysis {
    public static void main(String[] args) {

        System.out.println("       COMPLEXITY ANALYSIS");
        System.out.println("       BUS RESERVATION SYSTEM");

        System.out.println();

        System.out.println("1. BST INSERTION");
        System.out.println("   Average Time : O(log n)");
        System.out.println("   Worst Time   : O(n)");
        System.out.println("   Space        : O(h)");

        System.out.println();

        System.out.println("2. BST SEARCH");
        System.out.println("   Best Time    : O(1)");
        System.out.println("   Average Time : O(log n)");
        System.out.println("   Worst Time   : O(n)");
        System.out.println("   Space        : O(h)");

        System.out.println();

        System.out.println("3. INORDER TRAVERSAL");
        System.out.println("   Time         : O(n)");
        System.out.println("   Space        : O(h)");

        System.out.println();

        System.out.println("4. STORE IN ARRAYLIST");
        System.out.println("   Time         : O(n)");
        System.out.println("   Space        : O(n)");

        System.out.println();

        System.out.println("5. SELECTION SORT");
        System.out.println("   Best Time    : O(n²)");
        System.out.println("   Average Time : O(n²)");
        System.out.println("   Worst Time   : O(n²)");
        System.out.println("   Space        : O(1)");

        System.out.println();

        System.out.println("n = Number of buses");
        System.out.println("h = Height of the BST");
        
    }
}